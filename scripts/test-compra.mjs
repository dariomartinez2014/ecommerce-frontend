import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const fuente = await readFile(new URL('../src/lib/compra.ts', import.meta.url), 'utf8');
const { outputText } = ts.transpileModule(fuente, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } });
const { CLAVE_COMPRA, confirmarCompra, leerCompra, totalCentavos } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
const producto = { id: 1, name: 'Arroz', price: '0.10', stock: 3, description: null, category: 'Abarrotes', image_url: null, created_at: '2026-10-30' };
const inicial = { items: [{ producto, cantidad: 3 }], ordenes: [] };
assert.equal(totalCentavos(inicial.items), 30);
const fin = confirmarCompra(inicial, 'SIM-1', '2026-10-30T14:00:00Z');
assert.equal(fin.items.length, 0);
assert.equal(fin.ordenes.length, 1);
assert.equal(fin.ordenes[0].totalCentavos, 30);
assert.equal(inicial.items.length, 1);
assert.throws(() => confirmarCompra(fin, 'SIM-2', '2026-10-30T14:00:00Z'), /vacío/);
producto.price = '999';
assert.equal(fin.ordenes[0].items[0].producto.price, '0.10');
let raw = JSON.stringify(fin);
const storage = { getItem(key) { assert.equal(key, CLAVE_COMPRA); return raw; } };
assert.deepEqual(leerCompra(storage), fin);
raw = '{';
assert.deepEqual(leerCompra(storage), { items: [], ordenes: [] });
raw = JSON.stringify({ items: [{ producto, cantidad: -2 }], ordenes: [] });
assert.deepEqual(leerCompra(storage).items, []);
raw = JSON.stringify({ items: [], ordenes: [{ ...fin.ordenes[0], totalCentavos: 1 }] });
assert.deepEqual(leerCompra(storage).ordenes, []);
assert.deepEqual(leerCompra({ getItem() { throw new Error('Bloqueado'); } }), { items: [], ordenes: [] });
assert.throws(() => confirmarCompra({ items: [{ producto, cantidad: 4 }], ordenes: [] }, 'SIM-3', '2026-10-30'), /cantidades/);
console.log('OK: totales exactos, comprobante inmutable, vaciado, doble confirmación, persistencia y datos inválidos.');
